"""Print crates/spektrafilm-math/src/colorspace_data.rs from colour-science.

Every RGB colour-space constant the engine uses comes from here: the
RGB <-> XYZ matrices, whitepoints, CCTF parameters, the CAT02/CAT16 cone
matrices with their inverses, and the CAM16 viewing conditions of the output
gamut compressor. Values are printed with Python's `repr`, which Rust parses
back to the same f64 bits, and inverses are computed the way colour computes
them (`np.linalg.inv`). Nothing is typed by hand.

colour-science is BSD-3-Clause (Colour Developers); see
https://github.com/colour-science/colour.

    ~/Projects/spektrafilm-env/bin/python -I scripts/gen_colorspaces.py \
        > crates/spektrafilm-math/src/colorspace_data.rs
"""

import functools

import colour
import numpy as np
from colour.adaptation import CHROMATIC_ADAPTATION_TRANSFORMS
from colour.appearance.cam16 import MATRIX_16
from colour.appearance.ciecam02 import (
    VIEWING_CONDITIONS_CIECAM02,
    achromatic_response_forward,
    degree_of_adaptation,
    post_adaptation_non_linear_response_compression_forward,
    viewing_conditions_dependent_parameters,
)
from colour.models.rgb.transfer_functions import (
    davinci_intermediate,
    gamma,
    itur_bt_2020,
    linear,
    panasonic_v_log,
    rimm_romm_rgb,
    srgb,
)

COLOUR_VERSION = "0.4.7"
# Upstream's RGBColorSpaces (spektrafilm_gui/options.py at 28bf883, which
# added DaVinci Wide Gamut and V-Gamut in 8d4ff0f), plus ACEScg.
SPACES = [
    "sRGB", "DCI-P3", "Display P3", "Adobe RGB (1998)", "ITU-R BT.2020",
    "ProPhoto RGB", "ACES2065-1", "ACEScg", "DaVinci Wide Gamut", "V-Gamut",
]
# Other names colour accepts for these spaces, and Negs' older Rec. 2020 names.
ALIASES = {
    "Adobe RGB (1998)": ["adobe1998"],
    "ITU-R BT.2020": ["Rec. 2020", "Rec2020"],
    "ProPhoto RGB": ["prophoto"],
    "ACES2065-1": ["aces", "lin_ap0_scene"],
    "ACEScg": ["lin_ap1_scene"],
}
# The output gamut compressor's CAM16-UCS viewing conditions
# (spektrafilm/utils/gamut_compression.py: _CAM16UCS_L_A, _CAM16UCS_Y_B).
CAM16_L_A = 64.0
CAM16_Y_B = 20.0


def f(value):
    value = float(value)
    if not np.isfinite(value):
        raise ValueError(value)
    return repr(value)


def vec(values):
    return "[" + ", ".join(f(v) for v in values) + "]"


def mat(m, indent=0):
    m = np.asarray(m, dtype=np.float64)
    assert m.shape == (3, 3)
    pad = " " * indent
    return "[\n" + "".join(f"{pad}    {vec(row)},\n" for row in m) + f"{pad}]"


def cctf(cs):
    """The Rust `Cctf` for a colourspace's encoding/decoding pair."""
    enc, dec = cs.cctf_encoding, cs.cctf_decoding
    pairs = [
        (srgb.eotf_inverse_sRGB, srgb.eotf_sRGB, "Cctf::Srgb"),
        (itur_bt_2020.oetf_BT2020, itur_bt_2020.oetf_inverse_BT2020, "Cctf::Bt2020"),
        (rimm_romm_rgb.cctf_encoding_ROMMRGB, rimm_romm_rgb.cctf_decoding_ROMMRGB, "Cctf::Romm"),
        (linear.linear_function, linear.linear_function, "Cctf::Linear"),
        (panasonic_v_log.log_encoding_VLog, panasonic_v_log.log_decoding_VLog, "Cctf::VLog"),
        (davinci_intermediate.oetf_DaVinciIntermediate,
         davinci_intermediate.oetf_inverse_DaVinciIntermediate, "Cctf::DaVinciIntermediate"),
    ]
    for e, d, name in pairs:
        if enc is e and dec is d:
            return name
    if (isinstance(enc, functools.partial) and enc.func is gamma.gamma_function
            and isinstance(dec, functools.partial) and dec.func is gamma.gamma_function):
        assert set(enc.keywords) == {"exponent"} == set(dec.keywords) and not enc.args and not dec.args
        return f"Cctf::Gamma {{ encode: {f(enc.keywords['exponent'])}, decode: {f(dec.keywords['exponent'])} }}"
    raise ValueError(f"{cs.name}: unsupported CCTF {enc!r}/{dec!r}")


def xy_to_xyz_unit_y(xy):
    """gamut_compression._xy_to_xyz_unit_y."""
    x, y = xy
    safe_y = np.fmax(y, 1e-12)
    return np.array([x / safe_y, 1.0, (1.0 - x - y) / safe_y])


def cam16_white(xyz_w_unit):
    """`D_RGB` and `A_w` of colour.XYZ_to_CAM16 for the compressor's
    viewing conditions (XYZ_to_CAM16UCS scales XYZ_w by 100)."""
    surround = VIEWING_CONDITIONS_CIECAM02["Average"]
    xyz_w = np.asarray(xyz_w_unit) * 100
    y_w = xyz_w[1]
    rgb_w = colour.algebra.vecmul(MATRIX_16, xyz_w)
    d = np.clip(degree_of_adaptation(surround.F, CAM16_L_A), 0, 1)
    _n, f_l, n_bb, _n_cb, _z = viewing_conditions_dependent_parameters(CAM16_Y_B, y_w, CAM16_L_A)
    d_rgb = d * y_w / rgb_w + 1 - d
    rgb_aw = post_adaptation_non_linear_response_compression_forward(d_rgb * rgb_w, f_l)
    a_w = achromatic_response_forward(rgb_aw, n_bb)
    return d_rgb, a_w


def main():
    out = []
    p = out.append
    p("// @generated by scripts/gen_colorspaces.py from colour-science "
      f"{COLOUR_VERSION} — do not edit.")
    p("// colour-science is BSD-3-Clause (Colour Developers).")
    p("")
    p("use super::colorspace::{Cctf, RgbColourspace};")
    p("")
    for name in ["CAT02", "CAT16"]:
        m = CHROMATIC_ADAPTATION_TRANSFORMS[name]
        p(f"/// colour's `CHROMATIC_ADAPTATION_TRANSFORMS[\"{name}\"]`.")
        p(f"pub const {name}: [[f64; 3]; 3] = {mat(m)};")
        p(f"/// `np.linalg.inv({name})`, as `matrix_chromatic_adaptation_VonKries` computes it.")
        p(f"pub const {name}_INVERSE: [[f64; 3]; 3] = {mat(np.linalg.inv(m))};")
        p("")

    surround = VIEWING_CONDITIONS_CIECAM02["Average"]
    n, f_l, n_bb, n_cb, z = viewing_conditions_dependent_parameters(CAM16_Y_B, 100.0, CAM16_L_A)
    d = np.clip(degree_of_adaptation(surround.F, CAM16_L_A), 0, 1)
    assert np.allclose(MATRIX_16, CHROMATIC_ADAPTATION_TRANSFORMS["CAT16"], rtol=0, atol=0)
    p(f"// CAM16 viewing conditions of the output gamut compressor: L_A = {CAM16_L_A}, "
      f"Y_b = {CAM16_Y_B}, Average surround, Y_w = 100.")
    p("// The white-dependent D_RGB and A_w are per colourspace below.")
    p(f"pub const CAM16_F_L: f64 = {f(f_l)};")
    p(f"pub const CAM16_N: f64 = {f(n)};")
    p(f"pub const CAM16_N_BB: f64 = {f(n_bb)};")
    p(f"pub const CAM16_N_CB: f64 = {f(n_cb)};")
    p(f"pub const CAM16_Z: f64 = {f(z)};")
    p(f"pub const CAM16_C: f64 = {f(surround.c)};")
    p(f"pub const CAM16_N_C: f64 = {f(surround.N_c)};")
    p(f"pub const CAM16_D: f64 = {f(d)};")
    p("")

    bt = itur_bt_2020.CONSTANTS_BT2020
    a, b = bt.alpha(False), bt.beta(False)
    p("// ITU-R BT.2020 OETF (10-bit system constants).")
    p(f"pub const BT2020_ALPHA: f64 = {f(a)};")
    p(f"pub const BT2020_BETA: f64 = {f(b)};")
    p(f"/// `oetf_BT2020(beta)`, the decoding threshold.")
    p(f"pub const BT2020_DECODE_CUT: f64 = {f(itur_bt_2020.oetf_BT2020(b))};")
    p("/// `eotf_inverse_sRGB(0.0031308)`, the sRGB decoding threshold.")
    p(f"pub const SRGB_DECODE_CUT: f64 = {f(srgb.eotf_inverse_sRGB(0.0031308))};")
    p("// ROMM RGB (ProPhoto) at colour's default bit depth of 8.")
    p(f"pub const ROMM_I_MAX: f64 = {f(2 ** 8 - 1)};")
    p(f"pub const ROMM_E_T: f64 = {f(16 ** (1.8 / (1 - 1.8)))};")
    vl = panasonic_v_log.CONSTANTS_VLOG
    p("// Panasonic V-Log.")
    for key in ["cut1", "cut2", "b", "c", "d"]:
        p(f"pub const VLOG_{key.upper()}: f64 = {f(vl[key])};")
    di = davinci_intermediate.CONSTANTS_DAVINCI_INTERMEDIATE
    p("// DaVinci Intermediate.")
    for key in ["DI_A", "DI_B", "DI_C", "DI_M", "DI_LIN_CUT", "DI_LOG_CUT"]:
        p(f"pub const {key}: f64 = {f(di[key])};")
    p("")

    p("/// The colourspaces of `colour.RGB_COLOURSPACES` that the engine supports.")
    p(f"pub const COLOURSPACES: [RgbColourspace; {len(SPACES)}] = [")
    for name in SPACES:
        cs = colour.RGB_COLOURSPACES[name]
        assert cs.name == name
        wp = np.asarray(cs.whitepoint, dtype=np.float64)
        wp_xyz = colour.xyY_to_XYZ(colour.xy_to_xyY(wp))
        unit_y = xy_to_xyz_unit_y(wp)
        d_rgb, a_w = cam16_white(unit_y)
        same = colour.matrix_RGB_to_RGB(cs, cs)
        aliases = ", ".join(f'"{x}"' for x in ALIASES.get(name, []))
        p("    RgbColourspace {")
        p(f'        name: "{name}",')
        p(f"        aliases: &[{aliases}],")
        p(f"        whitepoint_xy: {vec(wp)},")
        p(f"        whitepoint_xyz: {vec(wp_xyz)},")
        p(f"        whitepoint_xyz_unit_y: {vec(unit_y)},")
        p(f"        rgb_to_xyz: {mat(cs.matrix_RGB_to_XYZ, 8)},")
        p(f"        xyz_to_rgb: {mat(cs.matrix_XYZ_to_RGB, 8)},")
        p(f"        rgb_to_rgb_self: {mat(same, 8)},")
        p(f"        cctf: {cctf(cs)},")
        p(f"        cam16_d_rgb: {vec(d_rgb)},")
        p(f"        cam16_a_w: {f(a_w)},")
        p("    },")
    p("];")
    print("\n".join(out))


if __name__ == "__main__":
    if colour.__version__ != COLOUR_VERSION:
        raise SystemExit(f"expected colour-science {COLOUR_VERSION}, found {colour.__version__}")
    main()
