//! Writes core/src/rules/facts/case_tables.odin: the Unicode tables the
//! photo facts' camera names need, read off this Rust's own `char` methods,
//! so the core lowercases, uppercases and trims exactly as the Rust it
//! replaces (`str::to_lowercase`'s final sigma included).
//!
//!     cargo run --release --manifest-path core/diff/Cargo.toml --bin case_tables \
//!         > core/src/rules/facts/case_tables.odin
//!
//! `core/diff/tests/photo_facts.rs` checks every scalar value against Rust.

fn scalars() -> impl Iterator<Item = char> {
    (0..=0x10ffffu32).filter_map(char::from_u32)
}

/// Ranges `[lo, hi]` of the scalars where `keep` holds.
fn ranges(keep: impl Fn(char) -> bool) -> Vec<(u32, u32)> {
    let mut out: Vec<(u32, u32)> = vec![];
    for c in scalars().filter(|&c| keep(c)) {
        let c = c as u32;
        match out.last_mut() {
            Some(last) if last.1 + 1 == c => last.1 = c,
            _ => out.push((c, c)),
        }
    }
    out
}

/// 1: cased and not case-ignorable; 2: case-ignorable; 0: neither, as
/// `str::to_lowercase`'s final-sigma test sees them.
fn sigma_class(c: char) -> u32 {
    if c == 'Σ' {
        return 1;
    }
    let ends_final = |s: String| s.to_lowercase().ends_with('ς');
    if ends_final(format!("{c}Σ")) {
        1
    } else if ends_final(format!("A{c}Σ")) {
        2
    } else {
        0
    }
}

fn main() {
    let version = std::process::Command::new("rustc").arg("--version").output().ok().map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string()).unwrap_or_default();
    println!("// Generated by core/diff/src/bin/case_tables.rs ({version}): do not edit.");
    println!("// Rust's char tables, so camera names are cased and trimmed as in Rust.");
    println!("package facts");
    println!();
    let white: Vec<u32> = scalars().filter(|c| c.is_whitespace()).map(|c| c as u32).collect();
    println!("// char::is_whitespace.");
    println!("@(rodata)\nWHITE_SPACE := [?]u32{{{}}}", white.iter().map(|c| format!("0x{c:x}")).collect::<Vec<_>>().join(", "));
    println!();
    let mut lower = vec![];
    let mut lower_long = vec![];
    for c in scalars() {
        let l: Vec<char> = c.to_lowercase().collect();
        if l.len() == 1 && l[0] == c {
            continue;
        }
        if l.len() == 1 {
            lower.push((c as u32, l[0] as u32));
        } else {
            lower_long.push((c as u32, l.iter().map(|&x| x as u32).collect::<Vec<_>>()));
        }
    }
    println!("// char::to_lowercase where it isn't the char itself and is one char.");
    println!("@(rodata)\nLOWER := [?][2]u32{{");
    for (c, l) in &lower {
        println!("\t{{0x{c:x}, 0x{l:x}}},");
    }
    println!("}}");
    println!();
    assert!(lower_long.iter().all(|(_, l)| l.len() <= 3));
    println!("// char::to_lowercase where it is more than one char (0 pads).");
    println!("@(rodata)\nLOWER_LONG := [?][4]u32{{");
    for (c, l) in &lower_long {
        let mut row = l.clone();
        row.resize(3, 0);
        println!("\t{{0x{c:x}, 0x{:x}, 0x{:x}, 0x{:x}}},", row[0], row[1], row[2]);
    }
    println!("}}");
    println!();
    let upper = ranges(|c| {
        let mut u = c.to_uppercase();
        !(u.next() == Some(c) && u.next().is_none())
    });
    println!("// Ranges of the chars whose char::to_uppercase isn't the char itself.");
    println!("@(rodata)\nUPPER_CHANGES := [?][2]u32{{");
    for (lo, hi) in &upper {
        println!("\t{{0x{lo:x}, 0x{hi:x}}},");
    }
    println!("}}");
    println!();
    let mut classes: Vec<(u32, u32, u32)> = vec![];
    for c in scalars() {
        let k = sigma_class(c);
        if k == 0 {
            continue;
        }
        let c = c as u32;
        match classes.last_mut() {
            Some(last) if last.1 + 1 == c && last.2 == k => last.1 = c,
            _ => classes.push((c, c, k)),
        }
    }
    println!("// Ranges [lo, hi, class] for str::to_lowercase's final sigma: 1 cased");
    println!("// (and not case-ignorable), 2 case-ignorable; others neither.");
    println!("@(rodata)\nSIGMA_CLASS := [?][3]u32{{");
    for (lo, hi, k) in &classes {
        println!("\t{{0x{lo:x}, 0x{hi:x}, {k}}},");
    }
    println!("}}");
}
