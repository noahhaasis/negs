//! Writes core/src/state/upper_tables.odin: `char::to_uppercase` read off
//! this Rust's own tables, so the state rules' titles (`option_title`,
//! edits' `words`) capitalise exactly as the Rust they replace.
//!
//!     cargo run --release --manifest-path core/diff/Cargo.toml --bin upper_tables \
//!         > core/src/state/upper_tables.odin
//!
//! `core/diff/tests/state_rules.rs` checks every scalar value against Rust.

fn main() {
    let version = std::process::Command::new("rustc").arg("--version").output().ok().map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string()).unwrap_or_default();
    println!("// Generated by core/diff/src/bin/upper_tables.rs ({version}): do not edit.");
    println!("// Rust's char::to_uppercase, for the titles the state rules capitalise.");
    println!("package state");
    println!();
    let mut one = vec![];
    let mut long = vec![];
    for c in (0..=0x10ffffu32).filter_map(char::from_u32) {
        let u: Vec<char> = c.to_uppercase().collect();
        if u.len() == 1 && u[0] == c {
            continue;
        }
        if u.len() == 1 {
            one.push((c as u32, u[0] as u32));
        } else {
            long.push((c as u32, u.iter().map(|&x| x as u32).collect::<Vec<_>>()));
        }
    }
    println!("// char::to_uppercase where it isn't the char itself and is one char.");
    println!("@(rodata)\nUPPER := [?][2]u32{{");
    for (c, u) in &one {
        println!("\t{{0x{c:x}, 0x{u:x}}},");
    }
    println!("}}");
    println!();
    assert!(long.iter().all(|(_, u)| u.len() <= 3));
    println!("// char::to_uppercase where it is more than one char (0 pads).");
    println!("@(rodata)\nUPPER_LONG := [?][4]u32{{");
    for (c, u) in &long {
        let mut row = u.clone();
        row.resize(3, 0);
        println!("\t{{0x{c:x}, 0x{:x}, 0x{:x}, 0x{:x}}},", row[0], row[1], row[2]);
    }
    println!("}}");
}
